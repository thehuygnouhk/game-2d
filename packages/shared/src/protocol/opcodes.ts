export type Opcode = (typeof Op)[keyof typeof Op];
const NAMES = new Map<number, string>(Object.entries(Op).map(([k, v]) => [v, k]));
export const opName = (op: number): string => NAMES.get(op) ?? `0x${op.toString(16).padStart(4, "0")}`;
